  function applyDocument(root = document) {
    if (!root) return;
    const contentPage = !isExtensionPage();
    translateNode(root.documentElement || root, contentPage);
    document.documentElement.lang = language;
  }

  function translateNode(root, contentPage) {
    if (!root) return;
    if (root.nodeType === Node.TEXT_NODE) {
      translateTextNode(root, contentPage);
      return;
    }
    if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;
    if (contentPage && root.nodeType === Node.ELEMENT_NODE && !isExtensionUi(root)) {
      for (const extensionRoot of root.querySelectorAll?.(".lingolayer-ui, #lingolayer-root") || []) {
        if (extensionRoot.parentElement?.closest(".lingolayer-ui, #lingolayer-root")) continue;
        translateNode(extensionRoot, true);
      }
      return;
    }

    if (root.nodeType === Node.ELEMENT_NODE) translateAttributes(root, contentPage);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) translateTextNode(node, contentPage);
    if (root.querySelectorAll) {
      for (const element of root.querySelectorAll(ATTRIBUTES.map((name) => `[${name}]`).join(","))) {
        translateAttributes(element, contentPage);
      }
    }
  }

  function translateTextNode(node, contentPage) {
    const parent = node.parentElement;
    if (!parent || parent.matches(PROTECTED_SELECTORS) || parent.closest(PROTECTED_SELECTORS)) return;
    if (contentPage && !isExtensionUi(parent)) return;
    const translated = translateText(node.nodeValue);
    if (translated !== node.nodeValue) node.nodeValue = translated;
  }

  function translateAttributes(element, contentPage) {
    if (contentPage && !isExtensionUi(element)) return;
    for (const attribute of ATTRIBUTES) {
      if (!element.hasAttribute(attribute)) continue;
      const value = element.getAttribute(attribute);
      const translated = translateText(value);
      if (translated !== value) element.setAttribute(attribute, translated);
    }
  }

  function isExtensionUi(element) {
    return Boolean(element?.closest?.(".lingolayer-ui, #lingolayer-root"));
  }

  function isExtensionPage() {
    if (typeof document !== "undefined" && document.documentElement?.dataset.vertapaneSurface) {
      return true;
    }
    if (typeof location === "undefined") return false;
    try {
      return location.href.startsWith(chrome.runtime.getURL(""));
    } catch {
      return false;
    }
  }

  function observeDocument() {
    observer?.disconnect();
    const contentPage = !isExtensionPage();
    observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === "characterData") {
          translateTextNode(mutation.target, contentPage);
          continue;
        }
        if (mutation.type === "attributes") {
          translateAttributes(mutation.target, contentPage);
          continue;
        }
        for (const node of mutation.addedNodes) translateNode(node, contentPage);
      }
    });
    observer.observe(document.documentElement, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ATTRIBUTES
    });
  }

  async function setPreference(value) {
    preference = normalizePreference(value);
    language = resolveLanguage(preference);
    await chrome.storage.local.set({ uiLanguage: preference });
    if (typeof document !== "undefined") applyDocument();
    return language;
  }

  function getLanguage() {
    return language;
  }

  function getLocale() {
    return language === "en" ? "en-US" : "ko-KR";
  }

  if (typeof chrome !== "undefined" && chrome.storage?.onChanged) {
    chrome.storage.onChanged.addListener((changes, areaName) => {
      if (areaName !== "local" || !changes.uiLanguage) return;
      preference = normalizePreference(changes.uiLanguage.newValue);
      language = resolveLanguage(preference);
      if (typeof document !== "undefined") applyDocument();
    });
  }

